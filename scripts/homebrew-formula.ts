/**
 * Generates the Homebrew formula for zanthrash/homebrew-tap from a release's checksums.
 *
 * Usage (from the release workflow):
 *   node scripts/homebrew-formula.ts <version> <checksums.txt>  > Formula/script-hop.rb
 */
import { readFileSync } from 'node:fs'

export const TARGETS = ['darwin-arm64', 'darwin-x64', 'linux-arm64', 'linux-x64'] as const
export type Target = (typeof TARGETS)[number]
export type Checksums = Record<Target, string>

const REPO = 'zanthrash/script-hop'

/** Release asset file name for a target, e.g. `hop-v0.6.0-darwin-arm64.tar.gz`. */
export const assetName = (version: string, target: Target) => `hop-v${version}-${target}.tar.gz`

/** Read `sha256sum`-style lines (`<sha>  <file>`) into checksums per target. */
export function parseChecksums(text: string, version: string): Checksums {
  const byFile = new Map(
    text.split('\n').map((l) => l.trim().split(/\s+\*?/)).filter((p) => p.length === 2).map(([sha, file]) => [file, sha]),
  )
  return Object.fromEntries(TARGETS.map((t) => [t, byFile.get(assetName(version, t))])) as Checksums
}

export function formula(version: string, sums: Checksums): string {
  for (const t of TARGETS) {
    if (!/^[0-9a-f]{64}$/.test(sums[t] ?? '')) throw new Error(`missing or invalid sha256 for ${t}`)
  }
  const asset = (t: Target) =>
    `url "https://github.com/${REPO}/releases/download/v${version}/${assetName(version, t)}"\n` +
    `      sha256 "${sums[t]}"`

  return `# Generated by script-hop's release workflow; edits will be overwritten.
class ScriptHop < Formula
  desc "Fuzzy, frecency-ranked picker for your project's scripts and tasks"
  homepage "https://github.com/${REPO}"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
      ${asset('darwin-arm64')}
    end
    on_intel do
      ${asset('darwin-x64')}
    end
  end

  on_linux do
    on_arm do
      ${asset('linux-arm64')}
    end
    on_intel do
      ${asset('linux-x64')}
    end
  end

  def install
    bin.install "hop"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/hop --version")
  end
end
`
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const [version, checksumsFile] = process.argv.slice(2)
  if (!version || !checksumsFile) {
    console.error('usage: homebrew-formula.ts <version> <checksums.txt>')
    process.exit(2)
  }
  process.stdout.write(formula(version, parseChecksums(readFileSync(checksumsFile, 'utf8'), version)))
}
